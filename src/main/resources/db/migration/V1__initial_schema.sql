CREATE TABLE app_users (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                           email VARCHAR(254) NOT NULL,
                           name VARCHAR(100) NOT NULL,
                           password_hash VARCHAR(255) NOT NULL,
                           CONSTRAINT uk_app_user_email UNIQUE (email)
);

CREATE TABLE trains (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        active BOOLEAN NOT NULL,
                        name VARCHAR(255) NOT NULL,
                        train_number VARCHAR(10) NOT NULL,
                        CONSTRAINT uk_train_number UNIQUE (train_number)
);

CREATE TABLE stations (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          city VARCHAR(255) NOT NULL,
                          code VARCHAR(10) NOT NULL,
                          name VARCHAR(255) NOT NULL,
                          CONSTRAINT uk_station_code UNIQUE (code)
);

CREATE TABLE trips (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       journey_date DATE NOT NULL,
                       train_id BIGINT NOT NULL,
                       CONSTRAINT uk_trip_train_date UNIQUE (train_id, journey_date),
                       CONSTRAINT fk_trip_train FOREIGN KEY (train_id) REFERENCES trains(id)
);

CREATE TABLE seats (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       coach_number VARCHAR(255) NOT NULL,
                       seat_class VARCHAR(255) NOT NULL,
                       seat_number VARCHAR(255) NOT NULL,
                       train_id BIGINT NOT NULL,
                       CONSTRAINT uk_seat_train_coach_number
                           UNIQUE (train_id, coach_number, seat_number),
                       CONSTRAINT fk_seat_train FOREIGN KEY (train_id) REFERENCES trains(id)
);

CREATE TABLE train_stops (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             arrival_time TIME(0),
                             departure_time TIME(0),
                             fare_from_origin NUMERIC(10, 2) NOT NULL,
                             stop_order INTEGER NOT NULL,
                             station_id BIGINT NOT NULL,
                             train_id BIGINT NOT NULL,
                             CONSTRAINT uk_train_stop_order UNIQUE (train_id, stop_order),
                             CONSTRAINT uk_train_stop_station UNIQUE (train_id, station_id),
                             CONSTRAINT fk_train_stop_train FOREIGN KEY (train_id) REFERENCES trains(id),
                             CONSTRAINT fk_train_stop_station FOREIGN KEY (station_id) REFERENCES stations(id)
);

CREATE TABLE seat_inventory (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                hold_expires_at TIMESTAMP(6) WITH TIME ZONE,
                                hold_token VARCHAR(255),
                                status VARCHAR(255) NOT NULL,
                                seat_id BIGINT NOT NULL,
                                trip_id BIGINT NOT NULL,
                                CONSTRAINT seat_inventory_status_check
                                    CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED')),
                                CONSTRAINT uk_inventory_trip_seat UNIQUE (trip_id, seat_id),
                                CONSTRAINT fk_inventory_trip FOREIGN KEY (trip_id) REFERENCES trips(id),
                                CONSTRAINT fk_inventory_seat FOREIGN KEY (seat_id) REFERENCES seats(id)
);

CREATE INDEX idx_inventory_trip_status
    ON seat_inventory (trip_id, status);

CREATE TABLE bookings (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          booked_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                          pnr VARCHAR(12) NOT NULL,
                          seat_id BIGINT NOT NULL,
                          trip_id BIGINT NOT NULL,
                          user_id BIGINT,
                          CONSTRAINT uk_booking_pnr UNIQUE (pnr),
                          CONSTRAINT uk_booking_trip_seat UNIQUE (trip_id, seat_id),
                          CONSTRAINT fk_booking_trip FOREIGN KEY (trip_id) REFERENCES trips(id),
                          CONSTRAINT fk_booking_seat FOREIGN KEY (seat_id) REFERENCES seats(id),
                          CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES app_users(id)
);